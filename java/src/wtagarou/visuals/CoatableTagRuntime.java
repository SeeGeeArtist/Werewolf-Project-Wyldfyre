package wtagarou.visuals;

import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * 0.4.62: tags every metal melee weapon script with {@code wtagarou:coatable}
 * right after the item scripts are loaded, so silver_recipes.txt can use ONE
 * tag for the weapon slot of the forge and coat recipes.
 *
 * Why: B42 craftRecipe inputs filter by tag only. {@code HasMetal} is on foil,
 * cans and light bulbs, and {@code Sharpenable;SharpKnife;ChopTree} misses
 * every blunt metal weapon, so the crafting window listed junk as "possible
 * items" while OnTest refused it. There is no "is a weapon" input filter, but
 * tags live in a mutable set on each script item and {@code ItemTags} indexes
 * them once at load ({@code ItemTags.Init}), which is where CoatableTagPatch
 * calls {@link #afterInit(Object)}.
 *
 * Rule ({@link #decide}): item type WEAPON, not ranged, metal (MetalValue > 0,
 * the HasMetal tag, any Smeltable* tag, Sharpenable, or a short list of metal
 * weapons whose scripts carry none of those: the carving fork, the ice axe),
 * not a Material (spear heads) and nothing already silver by name.
 *
 * 0.4.63: the Oct 16 playtest found the smithing hammer, claw hammer and
 * carving fork missing from the coat list. Forge tools are now coatable like
 * any other metal weapon; a SECOND tag, {@code wtagarou:forgeable}
 * ({@link #forgeable}), is the coatable set minus Tongs/File/Hammer/ClubHammer
 * and is what the forge recipe's weapon slot uses, so its tool slots still
 * never compete with its weapon slot.
 *
 * 0.4.65: the recipes no longer reference these tags. A hosted co-op server
 * is a child JVM without ZombieBuddy, so nothing tags there and an input
 * written as {@code tags[wtagarou:coatable]} aborted world load ("Tag has no
 * items"). silver_recipes.txt now carries explicit lists generated by
 * tools/gen_coatable_lists.py from the same rule; the client keeps tagging
 * so WTAGarouSilverAmmo.reportRecipeDrift can log what the lists miss.
 */
public final class CoatableTagRuntime {
    public static final String TAG_ID = "wtagarou:coatable";
    public static final String FORGE_TAG_ID = "wtagarou:forgeable";
    /** forge tools: coatable, but never the forge recipe's weapon. */
    static final String[] FORGE_TOOL_TAGS = {"tongs", "file", "hammer", "clubhammer"};
    /** metal weapons whose B42 scripts carry no MetalValue/HasMetal/Smeltable/Sharpenable (lower-case script names). */
    static final Set<String> METAL_BY_NAME = Set.of("carvingfork2", "iceaxe");

    static volatile int tagged = 0, forgeTagged = 0, scanned = 0;
    static volatile String lastError = null;
    static volatile boolean observed = false;

    private CoatableTagRuntime() {}

    /** Pure rule over the script item's properties; tag names may be "base:tongs" or "Tongs". */
    public static boolean decide(boolean weapon, boolean ranged, float metalValue,
                                 Collection<?> tags, String displayCategory,
                                 String scriptName, String displayName) {
        if (!weapon || ranged) return false;
        boolean metal = metalValue > 0f
                || (scriptName != null && METAL_BY_NAME.contains(scriptName.trim().toLowerCase(Locale.ENGLISH)));
        if (tags != null) {
            for (Object t : tags) {
                String n = tagPath(t);
                if (n == null) continue;
                if (n.equals("hasmetal") || n.equals("sharpenable") || n.startsWith("smeltable")) metal = true;
            }
        }
        if (!metal) return false;
        if (displayCategory != null && displayCategory.equalsIgnoreCase("Material")) return false;
        if (hasSilver(scriptName) || hasSilver(displayName)) return false;
        return true;
    }

    /** Coatable AND not a forge tool: the forge recipe's weapon slot. */
    public static boolean forgeable(boolean weapon, boolean ranged, float metalValue,
                                    Collection<?> tags, String displayCategory,
                                    String scriptName, String displayName) {
        if (!decide(weapon, ranged, metalValue, tags, displayCategory, scriptName, displayName)) return false;
        return !isForgeTool(tags);
    }

    public static boolean isForgeTool(Collection<?> tags) {
        if (tags == null) return false;
        for (Object t : tags) {
            String n = tagPath(t);
            if (n == null) continue;
            for (String ex : FORGE_TOOL_TAGS) if (n.equals(ex)) return true;
        }
        return false;
    }

    static boolean hasSilver(String s) {
        return s != null && s.toLowerCase(Locale.ENGLISH).contains("silver");
    }

    /** "base:HasMetal" / "HasMetal" / ItemTag -> "hasmetal"; null for null tags. */
    public static String tagPath(Object tag) {
        if (tag == null) return null;
        String s = tag.toString();
        int i = s.indexOf(':');
        if (i >= 0) s = s.substring(i + 1);
        return s.trim().toLowerCase(Locale.ENGLISH);
    }

    /** ItemTags.Init(allItems) exit: add the tags to qualifying scripts and index them. */
    public static void afterInit(Object allItems) {
        observed = true;
        if (!(allItems instanceof List<?> items)) return;
        try {
            Object tag = resolveTag(TAG_ID);
            if (tag == null) { lastError = "tag " + TAG_ID + " could not be registered"; return; }
            Object forgeTag = resolveTag(FORGE_TAG_ID);
            if (forgeTag == null) { lastError = "tag " + FORGE_TAG_ID + " could not be registered"; return; }
            Class<?> itemTags = Class.forName("zombie.inventory.ItemTags");
            Field mapField = Reflect.field(itemTags, "tagItemMap");
            @SuppressWarnings("unchecked")
            Map<Object, ArrayList<Object>> map = (Map<Object, ArrayList<Object>>) mapField.get(null);
            ArrayList<Object> indexed = map.computeIfAbsent(tag, k -> new ArrayList<>());
            ArrayList<Object> forgeIndexed = map.computeIfAbsent(forgeTag, k -> new ArrayList<>());
            int count = 0, forgeCount = 0, seen = 0;
            for (Object item : items) {
                if (item == null) continue;
                seen++;
                int level = qualifies(item);
                if (level <= 0) continue;
                @SuppressWarnings("unchecked")
                Set<Object> tags = (Set<Object>) Reflect.call(item, "getTags");
                tags.add(tag);
                if (!indexed.contains(item)) indexed.add(item);
                count++;
                if (level >= 2) {
                    tags.add(forgeTag);
                    if (!forgeIndexed.contains(item)) forgeIndexed.add(item);
                    forgeCount++;
                }
            }
            scanned = seen;
            tagged = count;
            forgeTagged = forgeCount;
            lastError = null;
        } catch (Throwable t) {
            lastError = t.toString();
        }
    }

    /** 0 = not coatable, 1 = coatable, 2 = coatable and forgeable. */
    static int qualifies(Object item) throws ReflectiveOperationException {
        Object type = Reflect.call(item, "getItemType");
        // ItemType is a registry object; toString() is "base:weapon"
        boolean weapon = "weapon".equals(tagPath(type));
        boolean ranged = Boolean.TRUE.equals(Reflect.call(item, "isRanged"));
        float metal = ((Number) Reflect.get(item, "metalValue")).floatValue();
        Collection<?> tags = (Collection<?>) Reflect.call(item, "getTags");
        String category = null;
        try { Object c = Reflect.call(item, "getDisplayCategory"); category = c == null ? null : c.toString(); }
        catch (ReflectiveOperationException ignored) {}
        String name = String.valueOf(Reflect.call(item, "getName"));
        String display = null;
        try { Object d = Reflect.call(item, "getDisplayName"); display = d == null ? null : d.toString(); }
        catch (ReflectiveOperationException ignored) {}
        if (!decide(weapon, ranged, metal, tags, category, name, display)) return 0;
        return isForgeTool(tags) ? 1 : 2;
    }

    /** registries.lua registers the tag first; this is the fallback when it did not run yet. */
    static Object resolveTag(String id) throws ReflectiveOperationException {
        Class<?> itemTag = Class.forName("zombie.scripting.objects.ItemTag");
        Class<?> location = Class.forName("zombie.scripting.objects.ResourceLocation");
        Method of = location.getMethod("of", String.class);
        Object loc = of.invoke(null, id);
        Object tag = itemTag.getMethod("get", location).invoke(null, loc);
        if (tag == null) tag = itemTag.getMethod("register", String.class).invoke(null, id);
        return tag;
    }

    public static String status() {
        return "coatable tag: " + (observed ? "ItemTags.Init seen" : "ItemTags.Init NOT seen")
                + ", " + tagged + " of " + scanned + " item scripts tagged coatable, " + forgeTagged + " forgeable"
                + (lastError == null ? "" : ", error: " + lastError);
    }
}
